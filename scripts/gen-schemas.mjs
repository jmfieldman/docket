// Embeds spec/schema/*.json into src/schemas.generated.ts so the bundled CLI
// carries its schemas. Run by `pnpm run build`; `pnpm run check` fails if stale.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const dir = join(root, 'spec', 'schema')
const schemas = Object.fromEntries(readdirSync(dir).sort().map((f) => [f, JSON.parse(readFileSync(join(dir, f), 'utf8'))]))
const out = `// Generated by scripts/gen-schemas.mjs from spec/schema. Do not edit.\nexport const SCHEMAS: Record<string, object> = ${JSON.stringify(schemas, null, 2)}\n`
writeFileSync(join(root, 'src', 'schemas.generated.ts'), out)
