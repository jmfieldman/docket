// Embeds spec/schema/*.json and ui/index.html into generated modules so the
// bundled CLI carries them. Run by `pnpm run build`; `pnpm run check` fails if stale.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const dir = join(root, 'spec', 'schema')
const schemas = Object.fromEntries(readdirSync(dir).sort().map((f) => [f, JSON.parse(readFileSync(join(dir, f), 'utf8'))]))
writeFileSync(
  join(root, 'src', 'schemas.generated.ts'),
  `// Generated by scripts/gen-assets.mjs from spec/schema. Do not edit.\nexport const SCHEMAS: Record<string, object> = ${JSON.stringify(schemas, null, 2)}\n`
)
const html = readFileSync(join(root, 'ui', 'index.html'), 'utf8')
writeFileSync(join(root, 'src', 'ui.generated.ts'), `// Generated by scripts/gen-assets.mjs from ui/index.html. Do not edit.\nexport const UI_HTML: string = ${JSON.stringify(html)}\n`)
